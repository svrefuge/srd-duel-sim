"""Write the SRD PDF's plain text, one `<<<PAGE n>>>` marker per page, for grepping printed quotes.

Usage: python tools/extract_srd_text.py ../SRD_CC_v5.2.1.pdf out/reference/SRD_CC_v5.2.1.txt
Needs the pinned extractor dependency (tools/requirements.txt). The output is a search aid only;
data/ is still generated by tools/build_srd_data.py.
"""
import sys

import fitz

pdf, out = sys.argv[1], sys.argv[2]
with open(out, "w") as handle:
    for number, page in enumerate(fitz.open(pdf), start=1):
        handle.write(f"\n<<<PAGE {number}>>>\n{page.get_text()}")
